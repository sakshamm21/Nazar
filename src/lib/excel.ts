/**
 * Client-side Excel export. Model-type tools (DCF, comps, SIP, risk, correlation, DuPont) become
 * live spreadsheets: blue cells are inputs, black cells are formulas, so users can change an
 * assumption and watch the model recalculate. Other tools export as clean data sheets.
 * exceljs is loaded on demand so it never weighs down the chat page.
 */
import type ExcelJS from "exceljs";
import { TOOL_LABELS } from "./followups";

type WS = ExcelJS.Worksheet;
type WB = ExcelJS.Workbook;

const INPUT_FONT = { color: { argb: "FF1F4ED8" }, bold: true };
const INPUT_FILL: ExcelJS.Fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFFFF7D6" } };
const HEAD_FILL: ExcelJS.Fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF0B6E4E" } };
const HEAD_FONT = { color: { argb: "FFFFFFFF" }, bold: true };
const PCT = "0.00%";
const NUM = "#,##0.00";
const BIG = "#,##0";

const safeName = (s: string) => s.replace(/[\\/*?:[\]]/g, " ").slice(0, 31).trim() || "Sheet";

function uniqueSheet(wb: WB, name: string): WS {
  let n = safeName(name), k = 2;
  while (wb.getWorksheet(n)) n = safeName(`${name.slice(0, 27)} ${k++}`);
  return wb.addWorksheet(n);
}

function title(ws: WS, text: string, sub: string) {
  ws.getCell("A1").value = text;
  ws.getCell("A1").font = { bold: true, size: 14 };
  ws.getCell("A2").value = `${sub} · Generated by Nazar on ${new Date().toLocaleString()} · Source: Yahoo Finance (may be delayed) · We explain; you decide. Not investment advice`;
  ws.getCell("A2").font = { italic: true, color: { argb: "FF6B7280" }, size: 9 };
}

function header(ws: WS, row: number, labels: string[], startCol = 1) {
  labels.forEach((l, i) => {
    const c = ws.getCell(row, startCol + i);
    c.value = l;
    c.fill = HEAD_FILL;
    c.font = HEAD_FONT;
    c.alignment = { horizontal: i === 0 ? "left" : "right" };
  });
}

function input(ws: WS, addr: string, value: any, fmt?: string) {
  const c = ws.getCell(addr);
  c.value = value ?? null;
  c.font = INPUT_FONT;
  c.fill = INPUT_FILL;
  if (fmt) c.numFmt = fmt;
}

function formula(ws: WS, addr: string, f: string, result?: any, fmt?: string, bold = false) {
  const c = ws.getCell(addr);
  c.value = { formula: f, result: result ?? undefined } as any;
  if (fmt) c.numFmt = fmt;
  if (bold) c.font = { bold: true };
}

function label(ws: WS, addr: string, text: string, bold = false) {
  ws.getCell(addr).value = text;
  if (bold) ws.getCell(addr).font = { bold: true };
}

const col = (n: number) => {
  let s = "";
  for (n++; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
};

