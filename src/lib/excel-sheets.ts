/**
 * Plain data sheets to Excel, in the browser: a header row and rows, one sheet each. For reports and
 * exports that are tables, not models. exceljs is loaded on demand.
 */
export type Sheet = { name: string; title?: string; columns: { header: string; width?: number; format?: "inr" | "num" | "pct" | "date" | "text" }[]; rows: (string | number | null)[][] };

const FORMAT = { inr: "₹#,##0", num: "#,##0.####", pct: "0.0%", date: "yyyy-mm-dd", text: "@" } as const;

export async function downloadSheets(filename: string, sheets: Sheet[]) {
  const { default: ExcelJS } = await import("exceljs");
  const wb = new ExcelJS.Workbook();
  wb.creator = "Nazar";
  for (const s of sheets) {
    const ws = wb.addWorksheet(s.name.replace(/[\\/*?:[\]]/g, " ").slice(0, 31) || "Sheet");
    let r = 1;
    if (s.title) {
      ws.getCell(r, 1).value = s.title;
      ws.getCell(r, 1).font = { bold: true, size: 13 };
      ws.getCell(r + 1, 1).value = `Generated by Nazar on ${new Date().toLocaleString("en-IN")}. A record of your own entries and Nazar's arithmetic; not tax or investment advice.`;
      ws.getCell(r + 1, 1).font = { italic: true, size: 9, color: { argb: "FF6B7280" } };
      r += 3;
    }
    s.columns.forEach((c, i) => {
      const cell = ws.getCell(r, i + 1);
      cell.value = c.header;
      cell.font = { bold: true, color: { argb: "FFFFFFFF" } };
      cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF2B54F0" } };
      ws.getColumn(i + 1).width = c.width ?? Math.max(12, c.header.length + 2);
    });
    for (const row of s.rows) {
      r++;
      row.forEach((v, i) => {
        const cell = ws.getCell(r, i + 1);
        const f = s.columns[i]?.format;
        cell.value = f === "date" && typeof v === "string" ? new Date(`${v}T00:00:00Z`) : v;
        if (f && f !== "text") cell.numFmt = FORMAT[f];
      });
    }
  }
  const buf = await wb.xlsx.writeBuffer();
  const url = URL.createObjectURL(new Blob([buf], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename.replace(/[^\w.\- ]+/g, "_");
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
}
